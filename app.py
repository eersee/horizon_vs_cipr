@app.route('/')
def index():
    return render_template('index.html', tile_names=ordered_tiles, sections=sections)

@app.route('/api/slide/<int:slide_num>')
def get_slide(slide_num):
    img_url = image_exists(slide_num)
    if img_url:
        return jsonify({"has_image": True, "image_url": img_url, "content": None})
    else:
        data = slides_data.get(slide_num, {"content": "<p>Нет данных</p>"})
        return jsonify({
            "has_image": False,
            "image_url": None,
            "content": data.get("content", "<p>Нет описания</p>")
        })

